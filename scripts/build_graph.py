#!/usr/bin/env python3
"""Build the knowledge graph from node frontmatter.

Every Markdown file under the node directories starts with a frontmatter block:

    ---
    id: wf-plan-file-fresh-session
    type: workflow
    title: Plan file, then a fresh session
    summary: One line.
    tags: [context, handoff]
    sources: [49851138, 49852750]
    links:
      - relies-on: con-context-boundary
      - uses: tool-plannotator
    ---

From those blocks this script writes:
  graph/graph.json   nodes + typed edges, machine-readable
  graph/graph.mmd    Mermaid flowchart of the whole graph
  graph/GRAPH.md     the same flowchart in a Markdown fence (GitHub renders it)
  explorer/index.html  interactive page: graph, full notes, playbook (scripts/build_explorer.py)
  artifact/index.html  the same page as published to the Claude artifact (scripts/build_artifact.py)
  INDEX.md           every node by type, with in/out degree
and rewrites the generated "Links" section at the bottom of every node file
so each node shows its outgoing edges and its backlinks.

Usage: python3 scripts/build_graph.py [--check]
  --check  fail (exit 1) if any link is dangling or any output is stale.
Stdlib only.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NODE_DIRS = {
    "concepts": "concept",
    "workflows": "workflow",
    "tools": "tool",
    "anti-patterns": "anti-pattern",
    "sources": "source",
}
TYPE_ORDER = ["source", "concept", "workflow", "tool", "anti-pattern"]
TYPE_LABEL = {
    "source": "Sources",
    "concept": "Concepts",
    "workflow": "Workflows",
    "tool": "Tools",
    "anti-pattern": "Anti-patterns",
}
HN = "https://news.ycombinator.com/item?id="

# Comparison attributes (optional on every node). Values are checked against these sets, so the
# Compare table's filters stay meaningful. list=True means the field takes [a, b].
FACETS = {
    "stage": {"list": True, "label": "Stage", "values": ["intent", "planning", "execution", "review", "understanding", "context", "safety"],
              "help": "where in the work it applies"},
    "scale": {"list": True, "label": "Task size", "values": ["small", "feature", "large", "long-run"],
              "help": "task sizes it suits"},
    "effort": {"list": False, "label": "Effort", "values": ["low", "medium", "high"],
               "help": "human effort to adopt and run it"},
    "cost": {"list": False, "label": "Token cost", "values": ["low", "medium", "high"],
             "help": "extra model usage it adds"},
    "origin": {"list": False, "label": "Origin", "values": ["built-in", "third-party", "practice"],
               "help": "for tools: ships with Claude Code, external, or a general practice"},
}

# Controlled edge vocabulary. An unknown relation fails the build, so edges stay queryable.
# Read an edge as: <from> <relation> <to>.
RELATIONS = {
    "addresses": "works on the problem named by the target",
    "applies": "puts the target principle into practice",
    "relies-on": "only works because the target holds",
    "uses": "uses the target tool",
    "enables": "makes the target workflow possible or easier",
    "complements": "works well together with the target",
    "alternative-to": "can replace the target",
    "variant-of": "is a lighter or different form of the target",
    "refines": "is a more structured form of the target",
    "mitigates": "reduces the target anti-pattern",
    "instance-of": "is a specific case of the target",
    "exemplifies": "is a known example of the target anti-pattern",
    "critiqued-by": "has a failure mode described by the target",
    "tension-with": "pulls against the target; choose per situation",
    "relates-to": "is related without a stronger relation",
    "argues": "(source) makes the case for the target",
    "disputes": "(source) contains pushback against the target",
    "surfaces": "(source) is where the target idea comes from",
    "contains-statement": "(source) contains the primary statement behind the target",
    "discussed-in": "(source) is discussed in the target source",
}
BEGIN = "<!-- graph:links:begin (generated by scripts/build_graph.py; do not edit) -->"
END = "<!-- graph:links:end -->"


def parse_list(value):
    value = value.strip()
    if not (value.startswith("[") and value.endswith("]")):
        raise ValueError(f"expected [a, b] list, got {value!r}")
    return [v.strip() for v in value[1:-1].split(",") if v.strip()]


def parse_frontmatter(path):
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing frontmatter")
    meta, links, in_links = {}, [], False
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        if in_links and line.startswith("  - "):
            rel, _, target = line[4:].partition(":")
            links.append((rel.strip(), target.strip()))
            continue
        in_links = False
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if key == "links":
            in_links = True
        elif key in ("tags", "sources") or key in FACETS and FACETS[key]["list"]:
            meta[key] = parse_list(value)
        else:
            if len(value) >= 2 and value[0] == value[-1] == '"':
                value = value[1:-1]
            meta[key] = value
    for required in ("id", "type", "title", "summary"):
        if required not in meta:
            raise ValueError(f"{path}: frontmatter lacks {required!r}")
    meta["links"] = links
    meta["path"] = path.relative_to(ROOT).as_posix()
    return meta, text


def load_nodes():
    nodes = {}
    for d, expected_type in NODE_DIRS.items():
        for path in sorted((ROOT / d).glob("*.md")):
            meta, text = parse_frontmatter(path)
            if meta["type"] != expected_type:
                raise ValueError(f"{path}: type {meta['type']!r} but lives in {d}/")
            if meta["id"] in nodes:
                raise ValueError(f"duplicate id {meta['id']}")
            meta["_text"] = text
            nodes[meta["id"]] = meta
    return nodes


def cite_url(src):
    return f"{HN}{src}" if src.isdigit() else src


def cite_label(src):
    return src if src.isdigit() else re.sub(r"^https?://(www\.)?", "", src)[:50]


def rel_link(from_path, to_path):
    depth = from_path.count("/")
    return "../" * depth + to_path


def links_section(node, nodes, incoming):
    lines = [BEGIN, "## Links", ""]
    out = node["links"]
    if out:
        lines.append("**Outgoing**")
        lines.append("")
        for rel, target in out:
            t = nodes[target]
            lines.append(f"- *{rel}* → [{t['title']}]({rel_link(node['path'], t['path'])}) `{target}`")
        lines.append("")
    inc = incoming.get(node["id"], [])
    if inc:
        lines.append("**Backlinks**")
        lines.append("")
        for rel, source in sorted(inc, key=lambda x: (x[1], x[0])):
            s = nodes[source]
            lines.append(f"- [{s['title']}]({rel_link(node['path'], s['path'])}) `{source}` *{rel}* this")
        lines.append("")
    srcs = node.get("sources", [])
    if srcs:
        lines.append("**Evidence:** " + ", ".join(f"[{cite_label(s)}]({cite_url(s)})" for s in srcs))
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def with_links(text, section):
    if BEGIN in text:
        text = text[: text.index(BEGIN)].rstrip("\n") + "\n\n"
    else:
        text = text.rstrip("\n") + "\n\n"
    return text + section


def mermaid(nodes, edges):
    shape = {
        "source": ('[("', '")]'),
        "concept": ('(["', '"])'),
        "workflow": ('["', '"]'),
        "tool": ('[/"', '"/]'),
        "anti-pattern": ('{{"', '"}}'),
    }
    safe = {nid: re.sub(r"[^A-Za-z0-9_]", "_", nid) for nid in nodes}
    lines = ["flowchart LR"]
    for t in TYPE_ORDER:
        members = [n for n in nodes.values() if n["type"] == t]
        if not members:
            continue
        lines.append(f"  subgraph {t.replace('-', '_')}[{TYPE_LABEL[t]}]")
        for n in members:
            a, b = shape[t]
            title = n["title"].replace('"', "'")
            lines.append(f"    {safe[n['id']]}{a}{title}{b}")
        lines.append("  end")
    for e in edges:
        lines.append(f"  {safe[e['from']]} -- {e['rel']} --> {safe[e['to']]}")
    for t in TYPE_ORDER:
        lines.append(f"  class {','.join(safe[n['id']] for n in nodes.values() if n['type'] == t) or 'none'} {t.replace('-', '_')}")
    lines += [
        "  classDef source fill:#eee,stroke:#555",
        "  classDef concept fill:#e8f0ff,stroke:#3a5fcd",
        "  classDef workflow fill:#e9f7ec,stroke:#2e8b57",
        "  classDef tool fill:#fff4e0,stroke:#c77700",
        "  classDef anti_pattern fill:#fdeaea,stroke:#b22222",
    ]
    return "\n".join(lines) + "\n"


def compare_md(nodes, incoming):
    """Side-by-side tables of workflows, tools and anti-patterns on their comparison attributes."""
    def cell(n, key):
        v = n.get(key)
        return "—" if not v else ", ".join(v) if isinstance(v, list) else v

    def targets(n, rels, types):
        hits = [nodes[t]["title"] for r, t in n["links"] if r in rels and nodes[t]["type"] in types]
        return "; ".join(hits) or "—"

    lines = [
        "# Compare",
        "",
        "Generated by `scripts/build_graph.py` from node frontmatter. Do not edit by hand. The interactive",
        "version, with filters and sorting, is the **Compare** tab of [explorer/index.html](explorer/index.html).",
        "",
        "Attributes: " + "; ".join(f"**{s['label']}** = {s['help']} ({', '.join(s['values'])})" for s in FACETS.values()) + ".",
        "**Evidence** = comments and pages cited. Ratings are editorial judgments from the thread, not measurements.",
        "",
    ]
    tables = [
        ("Workflows", "workflow", ["stage", "scale", "effort", "cost"], "Addresses", {"addresses", "applies", "mitigates"}, {"concept", "anti-pattern"}),
        ("Tools", "tool", ["origin", "stage", "effort"], "Supports", {"enables", "instance-of", "addresses", "alternative-to"}, {"workflow", "concept", "tool"}),
        ("Anti-patterns", "anti-pattern", ["stage"], "Instance of", {"instance-of", "relates-to", "tension-with"}, {"concept"}),
    ]
    for heading, t, keys, rel_label, rels, types in tables:
        members = sorted((n for n in nodes.values() if n["type"] == t), key=lambda n: n["title"].lower())
        lines += [f"## {heading} ({len(members)})", ""]
        header = ["Name", *(FACETS[k]["label"] for k in keys), rel_label, "Evidence"]
        lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
        for n in members:
            row = [f"[{n['title']}]({n['path']})", *(cell(n, k) for k in keys), targets(n, rels, types), str(len(n.get("sources", [])))]
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")
    return "\n".join(lines)


def index_md(nodes, incoming):
    lines = [
        "# Index",
        "",
        "Generated by `scripts/build_graph.py` from node frontmatter. Do not edit by hand.",
        "",
        "Columns: **out** = edges this node declares, **in** = edges pointing at it. "
        "High **in** means many other nodes depend on or refer to it, so start there.",
        "",
    ]
    for t in TYPE_ORDER:
        members = sorted((n for n in nodes.values() if n["type"] == t), key=lambda n: n["title"].lower())
        if not members:
            continue
        lines += [f"## {TYPE_LABEL[t]} ({len(members)})", "", "| Node | Summary | out | in |", "|---|---|---|---|"]
        for n in members:
            lines.append(
                f"| [{n['title']}]({n['path']}) | {n['summary']} | {len(n['links'])} | {len(incoming.get(n['id'], []))} |"
            )
        lines.append("")
    hubs = sorted(nodes.values(), key=lambda n: -len(incoming.get(n["id"], [])))[:10]
    lines += ["## Hubs (most backlinks)", ""]
    for n in hubs:
        lines.append(f"1. [{n['title']}]({n['path']}) — {len(incoming.get(n['id'], []))} backlinks")
    lines.append("")
    rels = defaultdict(int)
    for n in nodes.values():
        for rel, _ in n["links"]:
            rels[rel] += 1
    lines += ["## Edge vocabulary", "", "Read an edge as *from — relation → to*.", "", "| Relation | Meaning | Count |", "|---|---|---|"]
    for rel, meaning in RELATIONS.items():
        lines.append(f"| {rel} | {meaning} | {rels.get(rel, 0)} |")
    lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    nodes = load_nodes()
    errors, edges, incoming = [], [], defaultdict(list)
    for n in nodes.values():
        for rel, target in n["links"]:
            pass
        for key, spec in FACETS.items():
            vals = n.get(key)
            if vals is None:
                continue
            for v in (vals if spec["list"] else [vals]):
                if v not in spec["values"]:
                    errors.append(f"{n['path']}: {key} value {v!r} not in {spec['values']}")
        for rel, target in n["links"]:
            if rel not in RELATIONS:
                errors.append(f"{n['path']}: unknown relation {rel!r} (add it to RELATIONS or use an existing one)")
                continue
            if target not in nodes:
                errors.append(f"{n['path']}: link {rel} -> {target} points at no node")
                continue
            edges.append({"from": n["id"], "rel": rel, "to": target})
            incoming[target].append((rel, n["id"]))
    manifest = ROOT / "sources" / "manifest.json"
    if manifest.exists():
        for slug, entry in json.loads(manifest.read_text())["sources"].items():
            if not entry.get("node"):
                errors.append(f"sources/manifest.json: {slug} has no source node yet (create sources/src-*.md and set \"node\")")
            elif entry["node"] not in nodes:
                errors.append(f"sources/manifest.json: {slug} names missing node {entry['node']}")
    orphans = [n["id"] for n in nodes.values() if not n["links"] and not incoming.get(n["id"])]
    errors += [f"orphan node (no edges): {o}" for o in orphans]
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    outputs = {}
    graph = {
        "nodes": [
            {k: n.get(k) for k in ("id", "type", "title", "summary", "tags", "sources", "path", *FACETS)}
            for n in sorted(nodes.values(), key=lambda n: (TYPE_ORDER.index(n["type"]), n["id"]))
        ],
        "edges": edges,
    }
    for node in graph["nodes"]:
        node["tags"] = node["tags"] or []
        node["sources"] = [cite_url(s) for s in (node["sources"] or [])]
    outputs[ROOT / "graph" / "graph.json"] = json.dumps(graph, indent=2) + "\n"
    mmd = mermaid(nodes, edges)
    outputs[ROOT / "graph" / "graph.mmd"] = mmd
    outputs[ROOT / "graph" / "GRAPH.md"] = (
        "# Full graph\n\nGenerated by `scripts/build_graph.py`. Shapes: cylinder = source, stadium = concept, "
        "rectangle = workflow, parallelogram = tool, hexagon = anti-pattern. For a readable subset, see the map "
        "in [README.md](../README.md); for machine use, [graph.json](graph.json).\n\n```mermaid\n" + mmd + "```\n"
    )
    outputs[ROOT / "INDEX.md"] = index_md(nodes, incoming)
    outputs[ROOT / "COMPARE.md"] = compare_md(nodes, incoming)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from build_artifact import HOLD_BACK, render as render_artifact
    from build_explorer import render as render_explorer

    explorer_args = (graph, {n["id"]: n["_text"] for n in nodes.values()}, (ROOT / "README.md").read_text(), RELATIONS, FACETS)
    outputs[ROOT / "explorer" / "index.html"] = render_explorer(*explorer_args)
    outputs[ROOT / "artifact" / "index.html"] = render_artifact(render_explorer(*explorer_args, fragment=True))
    missing = [h for h in HOLD_BACK if h not in nodes]
    if missing:
        sys.exit(f"scripts/build_artifact.py: HOLD_BACK names missing node(s): {', '.join(missing)}")
    for n in nodes.values():
        outputs[ROOT / n["path"]] = with_links(n["_text"], links_section(n, nodes, incoming))

    stale = [p for p, content in outputs.items() if not p.exists() or p.read_text() != content]
    if check:
        if stale:
            print("stale outputs (run scripts/build_graph.py):", file=sys.stderr)
            print("\n".join(f"  {p.relative_to(ROOT)}" for p in stale), file=sys.stderr)
            sys.exit(1)
        print(f"ok: {len(nodes)} nodes, {len(edges)} edges, all outputs current")
        return
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p])
    print(f"{len(nodes)} nodes, {len(edges)} edges; rewrote {len(stale)} files")


if __name__ == "__main__":
    main()
